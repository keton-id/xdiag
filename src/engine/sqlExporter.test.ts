import { describe, expect, it } from 'vitest';
import { exportSQL } from './sqlExporter';
import type { Relation, Schema } from '../types/schema';

const schema: Schema = {
  tables: [
    {
      id: 'users',
      name: 'users',
      note: "app's users",
      fields: [
        {
          id: 'users.id',
          name: 'id',
          type: 'bigint',
          primaryKey: true,
          unique: false,
          notNull: true,
          increment: true,
        },
        {
          id: 'users.email',
          name: 'email',
          type: 'varchar(255)',
          primaryKey: false,
          unique: true,
          notNull: true,
          increment: false,
          note: 'login',
        },
        {
          id: 'users.created_at',
          name: 'created_at',
          type: 'timestamp',
          primaryKey: false,
          unique: false,
          notNull: false,
          increment: false,
          default: '(now())',
        },
        {
          id: 'users.role',
          name: 'role',
          type: 'text',
          primaryKey: false,
          unique: false,
          notNull: false,
          increment: false,
          default: "'member'",
        },
      ],
    },
    {
      id: 'posts',
      name: 'posts',
      fields: [
        {
          id: 'posts.id',
          name: 'id',
          type: 'int',
          primaryKey: true,
          unique: false,
          notNull: false,
          increment: false,
        },
        {
          id: 'posts.user_id',
          name: 'user_id',
          type: 'int',
          primaryKey: false,
          unique: false,
          notNull: true,
          increment: false,
        },
      ],
    },
  ],
  relations: [
    {
      id: 'rel_1',
      cardinality: '1:N',
      from: { tableId: 'users', fieldId: 'users.id', fieldName: 'id' },
      to: { tableId: 'posts', fieldId: 'posts.user_id', fieldName: 'user_id' },
      onDelete: 'cascade',
      onUpdate: 'restrict',
    },
  ],
  enums: [{ id: 'status', name: 'status', values: [{ name: 'active' }, { name: 'inactive' }] }],
  tableGroups: [],
};

describe('exportSQL — PostgreSQL', () => {
  const { ddl, dialect } = exportSQL(schema, 'postgresql');

  it('reports the dialect', () => {
    expect(dialect).toBe('postgresql');
  });

  it('emits the postgres header and enum type', () => {
    expect(ddl).toContain('-- PostgreSQL DDL generated by xdiag');
    expect(ddl).toContain("CREATE TYPE \"status\" AS ENUM (\n  'active',\n  'inactive'\n);");
  });

  it('maps increment types to serials', () => {
    expect(ddl).toContain('"id" BIGSERIAL NOT NULL');
    expect(ddl).toContain('PRIMARY KEY ("id")');
  });

  it('renders unique, not-null, defaults and expressions', () => {
    expect(ddl).toContain('"email" VARCHAR(255) NOT NULL UNIQUE');
    expect(ddl).toContain('"created_at" TIMESTAMP DEFAULT now()');
    expect(ddl).toContain('"role" TEXT DEFAULT \'member\'');
  });

  it('quotes and escapes comments', () => {
    expect(ddl).toContain(`COMMENT ON TABLE "users" IS 'app''s users';`);
    expect(ddl).toContain(`COMMENT ON COLUMN "users"."email" IS 'login';`);
  });

  it('puts the foreign key on the many side with actions', () => {
    expect(ddl).toContain(
      'ALTER TABLE "posts"\n  ADD CONSTRAINT "fk_users_id"\n  FOREIGN KEY ("user_id")\n' +
        '  REFERENCES "users" ("id")\n  ON DELETE CASCADE\n  ON UPDATE RESTRICT;',
    );
  });

  it('uses a declared constraint name when present', () => {
    const named: Relation = { ...schema.relations[0], name: 'custom_fk' };
    expect(exportSQL({ ...schema, relations: [named] }, 'postgresql').ddl).toContain(
      'ADD CONSTRAINT "custom_fk"',
    );
  });

  it('skips foreign keys for N:M relations', () => {
    const many: Relation = { ...schema.relations[0], cardinality: 'N:M' };
    expect(exportSQL({ ...schema, relations: [many] }, 'postgresql').ddl).not.toContain('ALTER TABLE');
  });

  it('puts the FK on the from side for N:1', () => {
    const rel: Relation = {
      id: 'rel_2',
      cardinality: 'N:1',
      from: { tableId: 'posts', fieldId: 'posts.user_id', fieldName: 'user_id' },
      to: { tableId: 'users', fieldId: 'users.id', fieldName: 'id' },
    };
    const out = exportSQL({ ...schema, relations: [rel] }, 'postgresql').ddl;
    expect(out).toContain('ALTER TABLE "posts"');
    expect(out).toContain('REFERENCES "users" ("id")');
  });
});

describe('exportSQL — MySQL', () => {
  const { ddl } = exportSQL(schema, 'mysql');

  it('switches header, identifiers and types', () => {
    expect(ddl).toContain('-- MySQL DDL generated by xdiag');
    expect(ddl).toContain('`id` BIGINT NOT NULL AUTO_INCREMENT');
    expect(ddl).toContain('`created_at` TIMESTAMP DEFAULT now()');
  });

  it('omits enum types and comments', () => {
    expect(ddl).not.toContain('CREATE TYPE');
    expect(ddl).not.toContain('COMMENT ON');
  });
});

describe('exportSQL — empty schema', () => {
  it('emits only the header', () => {
    const empty: Schema = { tables: [], relations: [], enums: [], tableGroups: [] };
    expect(exportSQL(empty, 'postgresql').ddl.trim()).toBe('-- PostgreSQL DDL generated by xdiag');
  });
});
